# Error metrics
def report_errors(true, pred, label):
    true = np.asarray(true); pred = np.asarray(pred)
    mse = mean_squared_error(true, pred)
    mae = mean_absolute_error(true, pred)
    rel = np.abs(pred - true) / true
    print(f"{label:16s}: MSE={mse:10.4f}  MAE={mae:8.4f}  "
          f"mean rel={rel.mean()*100:6.2f}%  median rel={np.median(rel)*100:6.2f}%")
    return rel

