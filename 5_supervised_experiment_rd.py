# Implied-volatility inversion

def implied_vol(price, S, K, T, r):
    intrinsic = max(S - K * np.exp(-r * T), 0.0)
    if price <= intrinsic + 1e-8 or price <= 0:
        return np.nan
    try:
        return brentq(lambda s: black_scholes_call(S, K, T, r, s) - price,
                      1e-4, 5.0, maxiter=200)
    except Exception:
        return np.nan

market_data["market_implied_vol"] = market_data["sigma"]
market_data["NN_implied_vol"] = market_data.apply(
    lambda row: implied_vol(row["NN_price"], row["S"], row["K"], row["T"], row["r"]),
    axis=1)
