# ------------------------------------------------------------------------------------------------------------
# Black-Scholes price for a European call
def black_scholes_call(S, K, T, r, sigma):
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
# ------------------------------------------------------------------------------------------------------------
# Domain filtering -
# any combination producing a price at or below $0.01 is rejected
# and resampled, until N accepted samples are collected.

# Generating 50000 samples (Artificial data), exactly as in Experiment 1
N = 50000
price_floor = 0.01

S_list, K_list, T_list, r_list, sigma_list, price_list = [], [], [], [], [], []
n_rejected = 0
n_accepted = 0

while n_accepted < N:
    n_batch = N - n_accepted
    S_b = np.random.uniform(50, 150, n_batch)
    K_b = np.random.uniform(50, 150, n_batch)
    T_b = np.random.uniform(0.05, 2.0, n_batch)
    r_b = np.random.uniform(0.01, 0.06, n_batch)
    sigma_b = np.random.uniform(0.10, 0.60, n_batch)
    price_b = black_scholes_call(S_b, K_b, T_b, r_b, sigma_b)

    keep = price_b > price_floor
    n_rejected += (~keep).sum()
    n_accepted += keep.sum()

    S_list.append(S_b[keep]); K_list.append(K_b[keep]); T_list.append(T_b[keep])
    r_list.append(r_b[keep]); sigma_list.append(sigma_b[keep]); price_list.append(price_b[keep])

S = np.concatenate(S_list)[:N]
K = np.concatenate(K_list)[:N]
T = np.concatenate(T_list)[:N]
r = np.concatenate(r_list)[:N]
sigma = np.concatenate(sigma_list)[:N]
prices = np.concatenate(price_list)[:N]

print(f"Accepted {N} samples; rejected {n_rejected} combinations "
      f"({n_rejected / (N + n_rejected):.1%} rejection rate).")

data = pd.DataFrame({"S": S, "K": K, "T": T, "r": r,
                     "sigma": sigma, "price": prices})


# ------------------------------------------------------------------------------------------------------------
# Training/testing data
#
# The real market data has no absolute scale: the index sits near 7786,
# while the artificial data uses S and K between 50 and 150. So here the
# network is given moneyness S/K instead of S and K, and is trained on
# sqrt(price/S) instead of the price. Both are scale-free, so the same
# network can be used at any index level

data["moneyness"] = data["S"] / data["K"]
X = data[["moneyness", "T", "r", "sigma"]].values
y = np.sqrt(data[["price"]].values / data[["S"]].values)

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=seed
)

#Standardization
scaler_X = StandardScaler()
scaler_y = StandardScaler()
X_train_scaled = scaler_X.fit_transform(X_train)
y_train_scaled = scaler_y.fit_transform(y_train)
X_test_scaled = scaler_X.transform(X_test)
y_test_scaled = scaler_y.transform(y_test)

#This script trains on float32.
X_train_tensor = torch.tensor(X_train_scaled, dtype=torch.float32)
y_train_tensor = torch.tensor(y_train_scaled, dtype=torch.float32)
X_test_tensor = torch.tensor(X_test_scaled, dtype=torch.float32)
y_test_tensor = torch.tensor(y_test_scaled, dtype=torch.float32)

train_ds = TensorDataset(X_train_tensor, y_train_tensor)
train_loader = DataLoader(train_ds, batch_size=256, shuffle=True)

# ------------------------------------------------------------------------------------------------------------
# Neural Network Architecture
# The neural network has 3 hidden layers, and each hidden layer contains 128 neurons.
# It takes 4 inputs here (moneyness, T, r, sigma) instead of the 5 used in Experiment 1.

class OptionPricingNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(4, 128), nn.ReLU(),
            nn.Linear(128, 128), nn.ReLU(),
            nn.Linear(128, 128), nn.ReLU(),
            nn.Linear(128, 1),
        )

    def forward(self, x):
        return self.network(x)


model = OptionPricingNN()
criterion = nn.MSELoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

# ------------------------------------------------------------------------------------------------------------
# Training loop

epochs = 1000
train_loss_history, test_loss_history = [], []
best_test_loss = float("inf")
best_state = None

print("\nTraining on the Experiment-1 synthetic dataset "
      "(scale-free representation)...")
for epoch in range(epochs):
    model.train()
    epoch_loss = 0.0
    for xb, yb in train_loader:
        optimizer.zero_grad()
        loss = criterion(model(xb), yb)
        loss.backward()
        optimizer.step()
        epoch_loss += loss.item() * len(xb)
    epoch_loss /= len(train_ds)

    model.eval()
    with torch.no_grad():
        test_loss = criterion(model(X_test_tensor), y_test_tensor).item()
    train_loss_history.append(epoch_loss)
    test_loss_history.append(test_loss)

    if test_loss < best_test_loss:
        best_test_loss = test_loss
        best_state = {k: v.clone() for k, v in model.state_dict().items()}

    if (epoch + 1) % 100 == 0:
        print(f"Epoch {epoch+1}/{epochs}  train={epoch_loss:.6f}  "
              f"test={test_loss:.6f}  best={best_test_loss:.6f}")

model.load_state_dict(best_state)
print(f"Training complete. Best test loss (restored): {best_test_loss:.6f}")

